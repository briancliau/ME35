current = [45.0, 45.0]

def move_servos(s1, s2):
    servo_motor_1_move(s1)
    servo_motor_2_move(s2)
    current[0], current[1] = s1, s2

def travel_to(s1, s2, steps=10, delay=0.03):
    """Glide to a start point with the LED OFF so no stray line is drawn."""
    a, b = current
    for i in range(1, steps + 1):
        move_servos(a + (s1 - a) * i / steps, b + (s2 - b) * i / steps)
        time.sleep(delay)

def draw_path(path_angles, step_delay=0.1, settle=0.3):
    """Travel to the first point (LED off), then draw the stroke (LED on)."""
    try:
        led.value(0)
        start_s1, start_s2 = path_angles[0]
        travel_to(start_s1, start_s2)
        time.sleep(settle)          # let the arm stop shaking before drawing
        led.value(1)                # LED only on while drawing
        for s1, s2 in path_angles:
            move_servos(s1, s2)
            time.sleep(step_delay)
    finally:
        led.value(0)                # always off afterwards, even on Ctrl-C or an error

def go_home():
    led.value(0)
    travel_to(45, 45)

def draw_robot():
    print("Starting robot drawing...")
    draw_path(HEAD_ANGLES)
    draw_path(EAR_LEFT_ANGLES)
